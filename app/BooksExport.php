<?php

namespace App;

use Carbon\CarbonImmutable;
use RuntimeException;
use ZipArchive;

class BooksExport
{
    /** @param array<string, mixed> $company
     * @return array<string, string>
     */
    public function headings(array $company, string $title, string $from, string $to, string $user): array
    {
        $start = CarbonImmutable::parse($from);
        $end = CarbonImmutable::parse($to);
        $month = $start->isStartOfMonth() && $end->isLastOfMonth() && $start->format('Y-m') === $end->format('Y-m');

        return [
            'company' => $company['registered_name'] ?? $company['company_name'],
            'trade' => 'Trade name: '.($company['trade_name'] ?? $company['company_name']),
            'tin' => (($company['vat_type'] ?? '') === 'vat' ? 'VAT REG TIN ' : 'NON-VAT REG TIN ').Tin::format($company['tin'] ?? '', $company['branch_code'] ?? '00000'),
            'address' => implode(', ', array_filter(array_map(fn (string $key): string => trim((string) ($company[$key] ?? '')), ['building', 'street', 'barangay', 'city', 'province', 'zip_code']))),
            'title' => $title,
            'period' => $month ? 'For the month of '.$start->format('F Y') : 'For the selected period',
            'range' => '('.$start->format('F j, Y').' - '.$end->format('F j, Y').')',
            'branch' => 'Branch: '.($company['branch_name'] ?? 'Main'),
            'printed' => 'Printed: '.now('Asia/Manila')->format('Y-m-d'),
            'footer' => 'Software: kontadurya.io - Generated by '.$user.' on '.now('Asia/Manila')->format('m/d/Y H:i:s').' PHT',
        ];
    }

    /** @param list<array{key: string, title: string, format?: string|null}> $columns
     * @param  list<array<string, mixed>>  $rows
     * @return list<array{cells: list<string|int|float|null>, kind: string}>
     */
    public function rows(array $columns, array $rows, string $book): array
    {
        $result = [];
        $totals = array_fill(0, count($columns), null);
        $totals[0] = 'Totals';
        if ($rows === []) {
            foreach ($columns as $index => $column) {
                if (($column['format'] ?? '') === 'money' && ! in_array($column['key'], ['balance', 'opening'], true)) {
                    $totals[$index] = 0;
                }
            }
        }
        $lastGroup = null;
        $lastVoucher = null;
        foreach ($rows as $row) {
            $kind = $row['kind'] ?? '';
            if (! empty($row['group']) && $lastGroup !== $row['group']) {
                $lastGroup = $row['group'];
                $lastVoucher = null;
                $heading = isset($row['groupAccount']) ? 'Account: '.$row['groupAccount'].(! empty($row['groupParty']) ? ' | Subsidiary: '.$row['groupParty'] : '') : $lastGroup;
                $result[] = ['cells' => [$heading], 'kind' => 'group'];
            }
            $cells = [];
            foreach ($columns as $index => $column) {
                $key = $column['key'];
                $value = $row[$key] ?? null;
                $money = ($column['format'] ?? '') === 'money';
                if ($money) {
                    if ($value !== null) {
                        $value = (int) $value / 100;
                    }
                    if ($value !== null && ! in_array($kind, ['opening', 'subtotal', 'closing'], true) && ! in_array($key, ['balance', 'opening'], true)) {
                        $totals[$index] = ($totals[$index] ?? 0) + (int) ($row[$key] ?? 0);
                    }
                    if ($kind === 'opening' && in_array($key, ['debit', 'credit'], true)) {
                        $value = null;
                    }
                    if ($book === 'general-journal' && in_array($key, ['debit', 'credit'], true) && $value == 0) {
                        $value = null;
                    }
                } elseif ($key === 'date' && $value) {
                    $value = CarbonImmutable::createFromFormat('!Y-m-d', $value)->format('m/d/Y');
                }
                if ($book === 'general-journal' && $lastVoucher !== null && $lastVoucher === ($row['voucherId'] ?? null) && in_array($key, ['date', 'number', 'reference', 'source', 'branch'], true)) {
                    $value = null;
                }
                if ($kind === 'opening' && in_array($key, ['date', 'branch'], true)) {
                    $value = null;
                }
                $cells[] = $value;
            }
            $lastVoucher = $row['voucherId'] ?? null;
            $result[] = ['cells' => $cells, 'kind' => $kind];
        }
        foreach ($columns as $index => $column) {
            if (($column['format'] ?? '') === 'money' && $totals[$index] !== null) {
                $totals[$index] /= 100;
            }
        }
        $result[] = ['cells' => $totals, 'kind' => 'total'];

        return $result;
    }

    /** @param array<string, string> $headings
     * @param  list<array{key: string, title: string, format?: string|null}>  $columns
     * @param  list<array{cells: list<string|int|float|null>, kind: string}>  $rows
     */
    public function workbook(array $headings, array $columns, array $rows): string
    {
        $path = tempnam(sys_get_temp_dir(), 'books-');
        $zip = new ZipArchive;
        if ($path === false || $zip->open($path, ZipArchive::OVERWRITE) !== true) {
            throw new RuntimeException('The Excel export could not be created.');
        }
        try {
            $namespace = 'http://schemas.openxmlformats.org/spreadsheetml/2006/main';
            $lastColumn = $this->column(count($columns));
            $sheet = '<worksheet xmlns="'.$namespace.'"><sheetPr><pageSetUpPr fitToPage="1"/></sheetPr><sheetViews><sheetView workbookViewId="0" showGridLines="0"><pane ySplit="10" topLeftCell="A11" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews><cols>';
            foreach ($columns as $index => $column) {
                $sheet .= '<col min="'.($index + 1).'" max="'.($index + 1).'" width="'.$this->width($column['key']).'" customWidth="1"/>';
            }
            $sheet .= '</cols><sheetData>';
            $headers = [$headings['company'], $headings['trade'], $headings['tin'], $headings['address'], $headings['title'], $headings['period'].' '.$headings['range'], $headings['branch'], $headings['printed']];
            foreach ($headers as $index => $heading) {
                $sheet .= '<row r="'.($index + 1).'">'.$this->cell('A'.($index + 1), $heading, in_array($index, [0, 4], true) ? 1 : 0).'</row>';
            }
            $sheet .= '<row r="10" ht="32" customHeight="1">';
            foreach ($columns as $index => $column) {
                $sheet .= $this->cell($this->column($index + 1).'10', $column['title'], 2);
            }
            $sheet .= '</row>';
            $merges = array_map(fn (int $number): string => 'A'.$number.':'.$lastColumn.$number, range(1, 8));
            foreach ($rows as $index => $row) {
                $number = $index + 11;
                $height = 18;
                foreach ($row['cells'] as $columnIndex => $value) {
                    $lines = array_sum(array_map(fn (string $line): int => max(1, (int) ceil(mb_strlen($line) / $this->width($columns[$columnIndex]['key']))), preg_split('/\R/u', (string) $value)));
                    $height = max($height, 14 * $lines + 4);
                }
                $sheet .= '<row r="'.$number.'" ht="'.($row['kind'] === 'group' ? 20 : min(409, $height)).'" customHeight="1">';
                if ($row['kind'] === 'group') {
                    $merges[] = 'A'.$number.':'.$lastColumn.$number;
                }
                foreach ($row['cells'] as $columnIndex => $value) {
                    $money = ($columns[$columnIndex]['format'] ?? '') === 'money';
                    $bold = in_array($row['kind'], ['group', 'subtotal', 'total', 'closing'], true);
                    $style = $bold ? ($money ? 5 : 4) : ($money ? 3 : 0);
                    $sheet .= $this->cell($this->column($columnIndex + 1).$number, $value, $style);
                }
                $sheet .= '</row>';
            }
            $lastRow = count($rows) + 13;
            $merges[] = 'A'.$lastRow.':'.$lastColumn.$lastRow;
            $sheet .= '<row r="'.$lastRow.'">'.$this->cell('A'.$lastRow, $headings['footer'], 0).'</row></sheetData>';
            if ($merges) {
                $sheet .= '<mergeCells count="'.count($merges).'">'.implode('', array_map(fn (string $range): string => '<mergeCell ref="'.$range.'"/>', $merges)).'</mergeCells>';
            }
            $sheet .= '<pageMargins left="0.35" right="0.35" top="0.4" bottom="0.4" header="0.2" footer="0.2"/><pageSetup paperSize="9" orientation="landscape" fitToWidth="1" fitToHeight="0"/><headerFooter><oddFooter>&amp;RPage &amp;P of &amp;N</oddFooter></headerFooter></worksheet>';
            $zip->addFromString('[Content_Types].xml', '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/><Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/></Types>');
            $zip->addFromString('_rels/.rels', '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>');
            $title = $this->xml(mb_substr($headings['title'], 0, 31));
            $zip->addFromString('xl/workbook.xml', '<workbook xmlns="'.$namespace.'" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="'.$title.'" sheetId="1" r:id="rId1"/></sheets><definedNames><definedName name="_xlnm.Print_Titles" localSheetId="0">\''.$title.'\'!$1:$10</definedName><definedName name="_xlnm.Print_Area" localSheetId="0">\''.$title.'\'!$A$1:$'.$lastColumn.'$'.$lastRow.'</definedName></definedNames></workbook>');
            $zip->addFromString('xl/_rels/workbook.xml.rels', '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/><Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/></Relationships>');
            $zip->addFromString('xl/worksheets/sheet1.xml', $sheet);
            $zip->addFromString('xl/styles.xml', $this->styles());
        } catch (\Throwable $exception) {
            $zip->close();
            unlink($path);
            throw $exception;
        }
        $zip->close();

        return $path;
    }

    public function width(string $key): int
    {
        return match ($key) {
            'remarks', 'address' => 36,
            'account', 'party', 'bank', 'offset' => 28,
            default => 18,
        };
    }

    public function pdfWidth(string $key): int
    {
        return match ($key) {
            'date' => 14,
            'number', 'source', 'customerType' => 12,
            'reference' => 14,
            'branch' => 8,
            'remarks', 'account' => 30,
            'address', 'offset' => 24,
            'party' => 20,
            'tin', 'bank' => 18,
            default => 13,
        };
    }

    private function cell(string $reference, string|int|float|null $value, int $style): string
    {
        $attributes = ' r="'.$reference.'" s="'.$style.'"';

        return is_int($value) || is_float($value)
            ? '<c'.$attributes.'><v>'.$value.'</v></c>'
            : '<c'.$attributes.' t="inlineStr"><is><t xml:space="preserve">'.$this->xml((string) $value).'</t></is></c>';
    }

    private function xml(string $value): string
    {
        return htmlspecialchars(preg_replace('/[\x00-\x08\x0B\x0C\x0E-\x1F]/u', '', $value), ENT_XML1 | ENT_QUOTES, 'UTF-8');
    }

    private function column(int $number): string
    {
        $name = '';
        while ($number > 0) {
            $name = chr(65 + ($number - 1) % 26).$name;
            $number = intdiv($number - 1, 26);
        }

        return $name;
    }

    private function styles(): string
    {
        $styles = '<styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><numFmts count="1"><numFmt numFmtId="164" formatCode="#,##0.00;(#,##0.00);0.00"/></numFmts><fonts count="2"><font><sz val="10"/><name val="Arial"/></font><font><b/><sz val="10"/><name val="Arial"/></font></fonts><fills count="3"><fill><patternFill patternType="none"/></fill><fill><patternFill patternType="gray125"/></fill><fill><patternFill patternType="solid"><fgColor rgb="FFE7E7E7"/><bgColor indexed="64"/></patternFill></fill></fills><borders count="1"><border/></borders><cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs><cellXfs count="6">';
        foreach ([[0, 0, 0], [1, 0, 0], [1, 2, 0], [0, 0, 164], [1, 2, 0], [1, 2, 164]] as [$font, $fill, $format]) {
            $styles .= '<xf fontId="'.$font.'" fillId="'.$fill.'" numFmtId="'.$format.'" borderId="0" xfId="0" applyNumberFormat="1" applyAlignment="1"><alignment vertical="top" wrapText="1"'.($format ? ' horizontal="right"' : '').'/></xf>';
        }

        return $styles.'</cellXfs><cellStyles count="1"><cellStyle name="Normal" xfId="0" builtinId="0"/></cellStyles></styleSheet>';
    }
}
