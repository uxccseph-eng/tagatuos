const confirmButton = document.querySelector('[data-confirm-vector]');
let salesConfirmed = false;
let activeLedger = 'sales';
function markSalesConfirmed() {
    const liveRow = ledgerRows?.querySelector('tr:last-child');
    const badge = liveRow?.querySelector('td:last-child span');
    if (badge) {
        badge.textContent = 'BALANCED';
        badge.className = 'inline-flex rounded-full bg-emerald-500/10 border border-emerald-500/30 px-2 py-0.5 text-[10px] text-emerald-400 font-semibold';
    }
    liveRow?.querySelector('.animate-ping')?.classList.remove('animate-ping');
}
document.querySelectorAll('[data-ledger-tab]').forEach((tab) => {
    tab.addEventListener('click', () => {
        activeLedger = tab.dataset.ledgerTab;
        document.querySelectorAll('[data-ledger-tab]').forEach((item) => item.setAttribute('aria-pressed', String(item === tab)));
        document.querySelector('[data-ledger-path]').textContent = `mesh://ph-bir.node.kontadurya.io/v4/${activeLedger}-matrix`;
        confirmButton.disabled = false;
        confirmButton.textContent = 'Confirm Vector';
        if (activeLedger === 'sales') {
            ledgerRows.innerHTML = originalSalesRows;
            document.querySelector('[data-tax-heading]').textContent = 'Output VAT (12%)';
            document.querySelector('[data-net-label]').textContent = 'Autonomously calculated net: ₱16,071.43';
            document.querySelector('[data-withholding-label]').textContent = 'EWT 2%: ₱321.43';
            if (salesConfirmed) {
                markSalesConfirmed();
                confirmButton.textContent = 'Vector Confirmed ✓';
                confirmButton.disabled = true;
            }
        } else {
            const sample = sampleLedgers[activeLedger];
            ledgerRows.replaceChildren();
            sample.entries.forEach((values) => {
                const row = document.createElement('tr');
                row.className = 'hover:bg-white/[0.02] transition-colors';
                [...values, 'BALANCED'].forEach((value, index) => {
                    const cell = document.createElement('td');
                    cell.textContent = value;
                    cell.className = `py-3.5 px-4 ${index >= 2 ? 'text-right' : ''} ${index === 4 ? 'text-emerald-400' : 'text-slate-300'}`;
                    row.append(cell);
                });
                ledgerRows.append(row);
            });
            document.querySelector('[data-tax-heading]').textContent = sample.tax;
            document.querySelector('[data-net-label]').textContent = sample.net;
            document.querySelector('[data-withholding-label]').textContent = sample.withholding;
        }
        document.querySelector('[data-ledger-status]').textContent = `${tab.textContent.trim()} sample selected.`;
    });
});
confirmButton?.addEventListener('click', () => {
    if (activeLedger === 'sales') {
        salesConfirmed = true;
        markSalesConfirmed();
    }
    confirmButton.textContent = 'Vector Confirmed ✓';
    confirmButton.disabled = true;
    document.querySelector('[data-ledger-status]').textContent = 'Sample vector confirmed. This is a visual demonstration; no transaction was saved.';
});

