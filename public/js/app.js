const resourceDialog = document.getElementById('resource-dialog');
document.querySelectorAll('[data-info]').forEach((link) => {
    link.addEventListener('click', (event) => {
        if (!resourceDialog?.showModal) return;
        event.preventDefault();
        const [title, description] = infoContent[link.dataset.info];
        document.getElementById('resource-title').textContent = title;
        document.getElementById('resource-description').textContent = description;
        resourceDialog.showModal();
    });
});
document.querySelector('[data-close-dialog]')?.addEventListener('click', () => resourceDialog.close());
resourceDialog?.addEventListener('click', (event) => {
    if (event.target === resourceDialog) {
        const bounds = resourceDialog.getBoundingClientRect();
        if (event.clientX < bounds.left || event.clientX > bounds.right || event.clientY < bounds.top || event.clientY > bounds.bottom) resourceDialog.close();
    }
});

